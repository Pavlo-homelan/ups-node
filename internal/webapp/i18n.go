func normalizeLanguage(language string) string {
	language = strings.ToLower(strings.TrimSpace(language))
	if language == "uk" || language == "en" {
		return language
	}
	return "uk"
}

func translate(language string, key string) string {
	language = normalizeLanguage(language)
	if value, ok := translations[language][key]; ok {
		return value
	}
	if value, ok := translations["en"][key]; ok {
		return value
	}
	return key
}

func clientTranslations(language string) map[string]string {
	keys := []string{
		"ups.state.CHARGE", "ups.state.DISCHARGE", "ups.state.CHARGED", "ups.state.IDLE",
		"ups.ac_ok", "ups.ac_lost",
		"ups.battery_status.full", "ups.battery_status.high", "ups.battery_status.medium",
		"ups.battery_status.low", "ups.battery_status.critical", "ups.battery_status.unknown",
		"ups.direction.charging", "ups.direction.discharging", "ups.direction.idle",
		"ups.mode.line", "ups.mode.backup", "ups.mains.online", "ups.mains.lost",
		"ups.load.line", "ups.load.battery", "ups.route.charger", "ups.route.load",
		"ups.summary.charging", "ups.summary.discharging", "ups.summary.full",
		"ups.summary.critical", "ups.summary.stable",
	}
	result := make(map[string]string, len(keys))
	for _, key := range keys {
		result[key] = translate(language, key)
	}
	return result
}
